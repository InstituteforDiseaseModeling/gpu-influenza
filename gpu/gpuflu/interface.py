def gpu_influenza_sampleI(params, quiet=True, debug=False, log="gpu-influenza"):

    # Initialization
    paramsInternal = params.copy()
    n = len(paramsInternal)
    
    # Get sampling probability
    if "p" in paramsInternal:
        p = paramsInternal["p"]
    elif "logP" in paramsInternal:
        p =  10**paramsInternal["logP"]
    else:
        p = numpy.ones(n)
    
    # Generate seeds for simulator
    paramsInternal["seed"] = numpy.random.randint( 0, 
                                                   numpy.iinfo(numpy.int32).max,
                                                   n, 
                                                   dtype="int"
                                                  )
    
    # Remove unnecessary fields from dataframe of parameters
    if "p" in paramsInternal:
        paramsInternal = paramsInternal.drop("p")
    if "logP" in paramsInternal:
        paramsInternal = paramsInternal.drop("logP")

    # Call model
    EIR = gpu_influenza( paramsInternal, quiet, debug, log )

    # Sampling
    I = EIR.filter( regex="^I", axis = 1 )
    Isampled = I.copy()
    for index in I.transpose():
        pThisSim = p[index]
        Isampled.loc[index,:] = numpy.random.binomial( \
                                             n = numpy.int32( I.loc[index,:] ),
                                             p = pThisSim 
                                )

    # Finalize and return
    return Isampled




