#---- gpu_influenza ------------------------------------------------------------
def gpu_influenza( params, quiet=True, debug=False, log="gpu-influenza" ):
    """Python interface to gpu-influenza model.
     Args:
      params : Pandas dataframe. Each row contains a set of parameters to be 
               used when calling gpu-influenza. The following gpu-influenza
               parameters should not be included in this dataframe: output, 
               network, quiet, and debug.
      quiet  : Enable/disable quiet mode (Boolean).
      debug  : Enable/disable debug mode (Boolean).
      log    : String that names the prefix of the execution log for each 
               call to gpu-influenza.
     Returns:
      Pandas dataframe with E, I, R, and incidence counts. The function also 
      writes all the standard output generated by the gpu-influenza code into 
      the file indicated by the 'log' argument.
    """

    # Init
    print( "... gpu_influenza: begin" )
    nTimesteps = int( params["time"].max() ) if ("time" in params.columns) else 10
    n = len(params)
    E_allSims = numpy.full( (n, nTimesteps), numpy.nan )
    I_allSims = numpy.full( (n, nTimesteps), numpy.nan )
    R_allSims = numpy.full( (n, nTimesteps), numpy.nan )
    incidence_allSims = numpy.full( (n, nTimesteps), numpy.nan ) 
    

    # Process all sets of parameters
    j = 0
    for index, row in params.iterrows():
    
        # Call GPU model
        logfilename = log + "_" + str(index) + ".log"
        gpuInfluenzaCmdArgs = buildArgs( index, row, quiet, debug )
        #print( "gpuInfluenzaCmdArgs = ", gpuInfluenzaCmdArgs )
        os.system(GPU_INFLUENZA_BIN + gpuInfluenzaCmdArgs + " > " + logfilename)
        #os.system(GPU_INFLUENZA_BIN + gpuInfluenzaCmdArgs)
        # Process data for current simulation

        transmissions = readTransmissions( index )
        #E_old, I_old, R_old = getCounts( transmissions, nTimesteps )
        partial_getCounts = partial(getCounts, nTimesteps=nTimesteps)
        E, I, R, incidence = multiprocessing_getCounts( transmissions, 
                                                        partial_getCounts
                                                       )

        # Update "allSims" arrays
        E_allSims[ index ] = E
        I_allSims[ index ] = I
        R_allSims[ index ] = R
        incidence_allSims[ index ] = incidence

        # Get ready for next set of parameters
        j = j+1
        if (j==1) or (j%10==0) or (j==n):
            print( "... gpu-influenza: ", j, "/", n )

    # Build output dataframe
    Eframe = pandas.DataFrame( E_allSims ).add_prefix( "E_" )
    Iframe = pandas.DataFrame( I_allSims ).add_prefix( "I_" )
    Rframe = pandas.DataFrame( R_allSims ).add_prefix( "R_" )
    incidence = pandas.DataFrame( incidence_allSims ).add_prefix("incidence_")
    EIR = pandas.concat( [Eframe, Iframe, Rframe, incidence], axis=1 )

    # Finalize and return
    print( "... gpu_influenza: finalized" )
    return EIR


