def buildArgs( index, 
               params : pandas.DataFrame,
               quiet, 
               debug 
              ):
    """Build line of command line arguments for gpu-influenza model.
    Args:
     index  : Integer with unique identifier for each set of parameters. In 
              general, this is the index of a pandas dataframe that contains a  
              group of sets of parameters.
     params : Pandas dataframe. Each row contains a set of parameters to be 
              converted into a command line string. The following gpu-influenza
              parameters should not be included in this dataframe: output, 
              network, quiet, and debug.
     quiet  : Enable/disable quiet mode (Boolean).
     debug  : Enable/disable debug mode (Boolean).
    """
     
    # Initialize parameter string
    cmdArgs = ""
    
    
    # Execution mode
    cmdArgs += " --quiet" if quiet else ""
    cmdArgs += " --debug" if debug else ""


    # Set name of output files and add to parameter string
    cmdArgs += " --output:"                        \
               + OUTPUT_FILENAME_PREFIX            \
               + str(index)                        \
               + ".bin"
    cmdArgs += " --network:"                       \
               + OUTPUT_NETWORK_FILENAME_PREFIX    \
               + str(index)                        \
               + ".bin"

    
    # Add other model parameters
    for key, value in params.items():
        #cmdArgs += " --" + key + ":" +str(int(value))
        cmdArgs += " --" + key + ":" +str(value)


    # Finalize and return
    return cmdArgs


def readTransmissions( index ):
    """Load the binary transmissions file indicated by index into a pandas
    dataframe.
     Args:
      index  : Integer with unique identifier for a set of parameters. It 
               defines the name of the file to read (the name of the file is 
               given by OUTPUT_FILENAME_PREFIX, followed by the index and then 
               the ".bin" extension.
     Returns:
      Dataframe with transmission data. 
    """
    filename = OUTPUT_FILENAME_PREFIX + str(index) + ".bin"

    transmissionsRaw = numpy.fromfile( filename, dtype=numpy.int32 )
    transmissions = pandas.DataFrame( transmissionsRaw.reshape( (-1, 4) ) )
    transmissions.columns = TRANSMISSION_COLUMNS
    #print(f"Read {filename} into dataframe.")

    return transmissions


def getCounts(transmissions, nTimesteps):
    """Compute the number of individuals on containers E, I, and R of the SEIR
    model at every timestep.
     Args:
      transmissions : Pandas dataframe with transmissions information. This
                      dataframe must contain the following columns:
                      "time_exposed", "time_infectious", "time_recovered".
      nTimesteps    : Integer with the number of timesteps expected to be found
                      in the transmissions data. This value also defines the
                      length of the arrays to be returned.
     Returns:
        E, I, R, and incidence numpy arrays, each of them containing the number 
        of subjects on their corresponding containers E, I, and R of the SEIR 
        model.
    """

    # Initialize (output and internal) arrays
    E = numpy.zeros((1, nTimesteps))
    I = numpy.zeros((1, nTimesteps))
    R = numpy.zeros((1, nTimesteps))
    incidence = numpy.zeros((1, nTimesteps))

    # Collect a dataframe that only contains row with at least one -1 value
    incomplete = transmissions < 0
    transmissions_complete = transmissions[~incomplete].dropna()
    # Use merge with indicator to remove transmissions_complete from transmissions and save it into a new dataframe
    transmissions_incomplete = transmissions.merge(transmissions_complete,
                                                   indicator=True, how='left').loc[lambda x : x['_merge']!='both']

    # Get incidence count by time
    e_counts = transmissions[TIME_EXPOSED].value_counts()
    i_counts = transmissions[TIME_INFECTIOUS].value_counts()
    r_counts = transmissions[TIME_RECOVERED].value_counts()

    # Get initial exposures, infections and recovered values
    r = i = e = 0  # Placeholder for (E, I, R) values at runtime.
    # Loop through all rows that contain -1 values
    for index, row in transmissions_incomplete.iterrows():
        if row[TIME_INFECTIOUS] == -1:
            if row[TIME_RECOVERED] > 0:
                # This is the the Initial infections
                i += 1
            if row[TIME_RECOVERED] == -1 and row[TIME_EXPOSED] == -1:
                # This is the susceptible individual who has -1 for all values
                e -= 1
    # Initial exposures
    e = e_counts[-1] - i + e if -1 in e_counts else 0

    # Loop through every timestep to get the E, I, R counts
    for t in range(nTimesteps):
        if t in e_counts:
            e += e_counts[t]

        if t in i_counts:
            i += i_counts[t]
            e -= i_counts[t]

        if t in r_counts:
            r += r_counts[t]
            i -= r_counts[t]

        E[0][t] += e
        I[0][t] += i
        R[0][t] += r

    #print("Count E, I and R numbers.")

    # Finalize and return
    #i_counts_nonNegIndex = i_counts.drop( index=[-1] )
    i_counts_nonNegIndex = i_counts.drop( index=[-1], errors="ignore" )
    numpy.put( incidence, i_counts_nonNegIndex.index, i_counts_nonNegIndex.values )
    return E, I, R, incidence


def multiprocessing_getCounts(df, func):
    # Create as many processes as there are CPUs on your machine
    # You may want to use "num_processes = multiprocessing.cpu_count() - 1" if you don't want to use all cpu
    num_processes = multiprocessing.cpu_count()

    # Split the dataframe into num_processes dataframes
    # It will work even if the length of the dataframe is not evenly divisible by num_processes
    df_split = numpy.array_split(df, num_processes)

    # Create our pool with `num_processes` processes
    pool = multiprocessing.Pool(processes=num_processes)

    # Apply our function to each chunk in the list of dataframes
    results = pool.map(func, df_split)
    # Terminate worker processes
    pool.close()
    # Wait for the worker processes to terminate.
    pool.join()

    # Add all results together
    E = results[0][0]
    I = results[0][1]
    R = results[0][2]
    incidence = results[0][3]
    for result in results[1:]:
        E = numpy.add(E, result[0])
        I = numpy.add(I, result[1])
        R = numpy.add(R, result[2])
        incidence = numpy.add(incidence, result[3])

    return E, I, R, incidence
